-- Magnitude analysis
-- Compare the measure values by categories. 
-- It helps us understand the importance of different categories.

-- 1. Find total customers by countries
SELECT 
    country,
    COUNT(DISTINCT customer_key) AS [Total_Customers]
FROM dbo.Customers
GROUP BY country
ORDER BY COUNT(customer_key) DESC; 


-- 2. Find the total customers by gender 
SELECT 
    gender, 
    COUNT(customer_key) AS [Total_Customers]
FROM dbo.Customers
GROUP BY gender; 


-- 2. Find total products by category 
SELECT 
    category,
    COUNT(product_name) AS [Total_Products]
FROM dbo.Products
GROUP BY category;


-- 3. What is the average costs in each category
SELECT 
    category, 
    ROUND(AVG(unit_price_usd),2) AS [Avg_Price]
FROM dbo.Products
GROUP BY category; 


-- 4. What is the total revenue generated for each category? 
SELECT 
    p.category, 
    SUM(s.Amount)/1000000 AS [Total_Revenue]
FROM dbo.Sales AS [s] 
LEFT JOIN dbo.Products AS [p]
ON s.product_key = p.product_key
GROUP BY p.category;


-- 5. Find total revenue is generated by each customer ?
SELECT 
    c.customer_key, 
    c.name,
    SUM(s.Amount) AS [Total_Customer]
FROM dbo.Sales AS [s]
LEFT JOIN dbo.Customers AS [c]
ON s.customer_key = c.customer_key
GROUP BY c.customer_key , c.name
ORDER BY [Total_Customer] DESC;


-- 6. What is the distribution of sold items across countries ? 
SELECT 
    c.country , 
    SUM(s.quantity) AS [Sold Items]
FROM Sales AS [s]
LEFT JOIN Customers AS [c]
ON s.customer_key = c.customer_key
GROUP BY c.country;

